import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { compile } from 'json-schema-to-typescript';

await mkdir('src/domain', { recursive: true });
for (const name of ['request', 'result']) {
  const schema = JSON.parse(await readFile(`contracts/document-${name}.schema.json`, 'utf8'));
  const source = await compile(schema, name === 'request' ? 'DocumentRequest' : 'DocumentResult', {
    bannerComment: '/* Generated by npm run generate:contracts. Edit contracts/*.schema.json instead. */',
    ignoreMinAndMaxItems: true,
    additionalProperties: false,
  });
  await writeFile(`src/domain/${name}.generated.ts`, source);
}
